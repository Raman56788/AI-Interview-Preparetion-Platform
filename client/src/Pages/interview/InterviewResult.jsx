import { useEffect, useState } from "react";
import { useNavigate } from "react-router-dom";
import {
  FaCheckCircle,
  FaHome,
  FaRedo,
  FaDownload,
  FaTrophy,
  FaCalendarAlt,
  FaUserTie,
} from "react-icons/fa";

import ScoreCircle from "../../components/interview/ScoreCircle";
import ScoreCard from "../../components/interview/ScoreCard";
import FeedbackCard from "../../components/interview/FeedbackCard";

const InterviewResult = () => {
  const navigate = useNavigate();

  // ================= STATE =================
  const [role, setRole] = useState("Frontend Developer");
  const [level, setLevel] = useState("Beginner");
  const [duration, setDuration] = useState("15 Minutes");
  const [questionsAnswered, setQuestionsAnswered] = useState(0);

  const [result, setResult] = useState({
    overallScore: 92,
    technicalScore: 95,
    communicationScore: 88,
    confidenceScore: 90,
    strengths: [],
    improvements: [],
    recommendation: "",
  });

  // ================= LOAD DATA =================
  useEffect(() => {
    const questions =
      JSON.parse(localStorage.getItem("questions")) || [];

    setRole(localStorage.getItem("role") || "Frontend Developer");
    setLevel(localStorage.getItem("level") || "Beginner");
    setDuration(localStorage.getItem("duration") || "15 Minutes");
    setQuestionsAnswered(questions.length);

    const savedResult = JSON.parse(
      localStorage.getItem("interviewResult")
    );

    if (savedResult) {
      setResult(savedResult);
    } else {
      // Demo Result (Fallback)
      setResult({
        overallScore: 92,
        technicalScore: 95,
        communicationScore: 88,
        confidenceScore: 90,

        strengths: [
          "Strong understanding of HTML, CSS and JavaScript fundamentals.",
          "Good confidence while explaining React concepts.",
          "Answered technical questions in a structured manner.",
        ],

        improvements: [
          "Explain real projects with problem → solution → result approach.",
          "Improve spoken English fluency and reduce pauses.",
          "Add more backend and SQL examples in technical answers.",
        ],

        recommendation:
          "Practice MERN Stack, React Hooks, SQL, DBMS and HR interview questions daily. Focus on explaining your AI Interview Preparation Platform confidently in interviews.",
      });
    }
  }, []);

  // ================= START AGAIN =================
  const startAgain = () => {
    localStorage.removeItem("questions");
    localStorage.removeItem("answers");
    localStorage.removeItem("interviewResult");

    navigate("/interview/setup");
  };

  // ================= DOWNLOAD REPORT =================
  const downloadReport = () => {
    const report = `
========== AI INTERVIEW REPORT ==========

Role : ${role}
Level : ${level}
Duration : ${duration}
Questions Answered : ${questionsAnswered}

-----------------------------------------
OVERALL SCORE : ${result.overallScore}%
-----------------------------------------

Technical Score      : ${result.technicalScore}%
Communication Score  : ${result.communicationScore}%
Confidence Score     : ${result.confidenceScore}%

============== STRENGTHS ==============

${result.strengths.join("\n")}

=========== NEEDS IMPROVEMENT ===========

${result.improvements.join("\n")}

=========== AI RECOMMENDATION ===========

${result.recommendation}

========================================
Generated by AI Interview Preparation Platform
========================================
`;

    const blob = new Blob([report], {
      type: "text/plain",
    });

    const url = URL.createObjectURL(blob);

    const link = document.createElement("a");
    link.href = url;
    link.download = "AI_Interview_Report.txt";
    link.click();

    URL.revokeObjectURL(url);
  };

  return (
    <div className="min-h-screen bg-gray-100 p-5 lg:p-8">
      <div className="max-w-7xl mx-auto space-y-8">

        {/* ================= HERO SECTION ================= */}
        <div className="bg-gradient-to-r from-green-600 via-green-500 to-emerald-500 rounded-3xl p-8 shadow-lg text-white">

          <div className="flex flex-col lg:flex-row justify-between items-center gap-6">

            <div className="flex items-center gap-5">
              <FaTrophy className="text-7xl text-yellow-300" />

              <div>
                <h1 className="text-4xl font-bold">
                  Interview Completed Successfully 🎉
                </h1>

                <p className="text-green-100 mt-2 text-lg">
                  Gemini AI evaluated your interview performance successfully.
                </p>
              </div>
            </div>

            <div className="bg-white/20 backdrop-blur-lg rounded-2xl px-6 py-4 text-center">
              <p className="text-green-100 text-sm">
                Overall AI Score
              </p>

              <h2 className="text-5xl font-bold">
                {result.overallScore}%
              </h2>
            </div>

          </div>
        </div>

        {/* ================= SCORE SECTION ================= */}
        <div className="grid lg:grid-cols-2 gap-6">

          <ScoreCircle score={result.overallScore} />

          <div className="grid grid-cols-2 gap-5">

            <ScoreCard
              title="Technical Skills"
              score={result.technicalScore}
              color="green"
            />

            <ScoreCard
              title="Communication"
              score={result.communicationScore}
              color="blue"
            />

            <ScoreCard
              title="Confidence"
              score={result.confidenceScore}
              color="purple"
            />

            <ScoreCard
              title="Overall Performance"
              score={result.overallScore}
              color="orange"
            />

          </div>
        </div>

        {/* ================= SUMMARY ================= */}
        <div className="bg-white rounded-3xl shadow-md p-8">

          <h2 className="text-2xl font-bold text-gray-800 mb-6">
            Interview Summary
          </h2>

          <div className="grid md:grid-cols-2 xl:grid-cols-4 gap-5">

            <div className="bg-green-50 rounded-2xl p-5">
              <FaUserTie className="text-green-600 text-3xl mb-3" />

              <p className="text-sm text-gray-500">Role</p>

              <h3 className="text-lg font-bold text-green-700">
                {role}
              </h3>
            </div>

            <div className="bg-blue-50 rounded-2xl p-5">
              <FaCheckCircle className="text-blue-600 text-3xl mb-3" />

              <p className="text-sm text-gray-500">
                Difficulty Level
              </p>

              <h3 className="text-lg font-bold text-blue-700">
                {level}
              </h3>
            </div>

            <div className="bg-purple-50 rounded-2xl p-5">
              <FaCalendarAlt className="text-purple-600 text-3xl mb-3" />

              <p className="text-sm text-gray-500">Duration</p>

              <h3 className="text-lg font-bold text-purple-700">
                {duration}
              </h3>
            </div>

            <div className="bg-orange-50 rounded-2xl p-5">
              <FaTrophy className="text-orange-500 text-3xl mb-3" />

              <p className="text-sm text-gray-500">
                Questions Answered
              </p>

              <h3 className="text-lg font-bold text-orange-600">
                {questionsAnswered}
              </h3>
            </div>

          </div>
        </div>

        {/* ================= FEEDBACK ================= */}
        <div className="grid lg:grid-cols-2 gap-6">

          <FeedbackCard
            title="Your Strengths"
            type="strength"
            points={result.strengths}
          />

          <FeedbackCard
            title="Needs Improvement"
            type="improvement"
            points={result.improvements}
          />

        </div>

        {/* ================= AI RECOMMENDATION ================= */}
        <FeedbackCard
          title="AI Recommendation"
          type="recommendation"
          points={[result.recommendation]}
        />

        {/* ================= PERFORMANCE MESSAGE ================= */}
        <div className="bg-gradient-to-r from-emerald-500 to-green-600 rounded-3xl p-8 text-white shadow-md">

          <h2 className="text-2xl font-bold mb-4">
            Performance Summary 🚀
          </h2>

          <p className="text-green-100 leading-8 text-lg">
            Your AI mock interview shows good technical knowledge and confidence.
            Continue practicing React, JavaScript, SQL, DBMS, DSA and HR
            questions. Regular mock interviews will improve communication and
            placement readiness.
          </p>

        </div>

        {/* ================= BUTTONS ================= */}
        <div className="grid md:grid-cols-3 gap-5">

          <button
            onClick={startAgain}
            className="bg-blue-600 hover:bg-blue-700 text-white py-4 rounded-2xl font-semibold flex justify-center items-center gap-3 transition"
          >
            <FaRedo />
            Start New Interview
          </button>

          <button
            onClick={downloadReport}
            className="bg-purple-600 hover:bg-purple-700 text-white py-4 rounded-2xl font-semibold flex justify-center items-center gap-3 transition"
          >
            <FaDownload />
            Download Report
          </button>

          <button
            onClick={() => navigate("/dashboard")}
            className="bg-green-600 hover:bg-green-700 text-white py-4 rounded-2xl font-semibold flex justify-center items-center gap-3 transition"
          >
            <FaHome />
            Go To Dashboard
          </button>

        </div>

      </div>
    </div>
  );
};

export default InterviewResult;